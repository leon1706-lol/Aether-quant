"""Hash-locked requirement files (V6.6.7, #361): every install in a workflow, Dockerfile or shell script reads one.

The OpenSSF Scorecard counts a pip install as pinned only with `--require-hashes` (or a wheel file, or `--no-deps -e .`).
Each profile `requirements/lock/<name>.in` compiles with uv into `<name>.txt`: exact pins, a sha256 for every file, one
universal resolution for CPython 3.11 on Linux and Windows (the CI interpreter). The `ci` and `runtime` profiles take
torch from the CPU index, so neither OS pulls the CUDA wheels.

    python scripts/lock_requirements.py                    # every profile
    python scripts/lock_requirements.py --profile ci       # one (repeatable)
    python scripts/lock_requirements.py --print            # the commands only

A Dependabot floor bump in `requirements/*.txt` needs this rerun on its branch: `tests/test_requirement_locks.py` fails
while a lock pin is below a floor.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK_DIR = ROOT / "requirements" / "lock"
PYTHON_VERSION = "3.11"
CPU_INDEX = "https://download.pytorch.org/whl/cpu"
PYPI_INDEX = "https://pypi.org/simple"


@dataclass(frozen=True)
class ProfileSpec:
    name: str
    torch_cpu: bool = False
    python_version: str = PYTHON_VERSION

    @property
    def in_path(self) -> Path:
        return LOCK_DIR / f"{self.name}.in"

    @property
    def out_path(self) -> Path:
        return LOCK_DIR / f"{self.name}.txt"


PROFILES: dict[str, ProfileSpec] = {
    spec.name: spec
    for spec in (
        ProfileSpec("ci", torch_cpu=True),
        ProfileSpec("runtime", torch_cpu=True),
        ProfileSpec("tools"),
        ProfileSpec("docs"),
        ProfileSpec("notebooks"),
        ProfileSpec("light"),
        ProfileSpec("dashboard"),
        ProfileSpec("build-ext"),
        ProfileSpec("lean-cli"),
        ProfileSpec("lean-runtime"),
        ProfileSpec("fuzz"),
        ProfileSpec("sanitize"),
        ProfileSpec("sbom"),
        ProfileSpec("compat", python_version="3.10"),
    )
}


def header(profile: ProfileSpec) -> str:
    return f"# generated by scripts/lock_requirements.py --profile {profile.name}; edit {profile.name}.in, never this file\n# install: python -m pip install --require-hashes -r requirements/lock/{profile.name}.txt\n"


def build_command(profile: ProfileSpec, *, uv: str = "uv") -> list[str]:
    command = [
        uv, "pip", "compile", str(profile.in_path), "--universal", "--python-version", profile.python_version,
        "--generate-hashes", "--no-header", "--quiet", "-o", str(profile.out_path),
    ]
    if profile.torch_cpu:
        # the +cpu wheels exist only on the CPU index, so the file carries both index lines for pip; the hashes make the
        # second index safe (a same-named upload elsewhere can't match them)
        command += ["--index-url", CPU_INDEX, "--extra-index-url", PYPI_INDEX, "--index-strategy", "unsafe-best-match", "--emit-index-url"]
    return command


def write_header(profile: ProfileSpec) -> None:
    body = profile.out_path.read_text(encoding="utf-8")
    profile.out_path.write_text(header(profile) + body, encoding="utf-8", newline="\n")


def find_uv(which: Callable[[str], str | None] = shutil.which) -> str:
    """uv on PATH, else the one next to this interpreter (a venv's Scripts/ or bin/)."""
    found = which("uv")
    if found:
        return found
    for name in ("uv.exe", "uv"):
        candidate = Path(sys.executable).with_name(name)
        if candidate.exists():
            return str(candidate)
    raise SystemExit("uv not found: python -m pip install uv")


def main(argv: Sequence[str] | None = None, *, run: Callable[..., subprocess.CompletedProcess] = subprocess.run) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--profile", action="append", choices=sorted(PROFILES), help="one profile (repeatable; default every profile with an .in file)")
    parser.add_argument("--print", action="store_true", dest="print_only", help="print the commands, run nothing")
    args = parser.parse_args(argv)
    chosen = [PROFILES[name] for name in (args.profile or PROFILES) if PROFILES[name].in_path.exists()]
    uv = "uv" if args.print_only else find_uv()
    for profile in chosen:
        command = build_command(profile, uv=uv)
        print(" ".join(command), flush=True)
        if args.print_only:
            continue
        if run(command, cwd=ROOT, check=False).returncode != 0:
            print(f"lock {profile.name}: uv failed", file=sys.stderr)
            return 1
        write_header(profile)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
