"""requirements/lock/ (V6.6.7, #361): every lock is hashed, generated from its .in, and satisfies every floor it inherits."""

from __future__ import annotations

import re
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.version import Version

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements" / "lock"


def _requirements(path: Path) -> list[Requirement]:
    """Every requirement an .in names, following `-r` includes (relative to the including file)."""
    out: list[Requirement] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("-r "):
            out += _requirements((path.parent / line[3:].strip()).resolve())
            continue
        out.append(Requirement(line))
    return out


def _pins(path: Path) -> dict[str, list[tuple[Version, str]]]:
    """name -> [(version, marker text)] from a compiled lock; each pin must carry at least one sha256."""
    pins: dict[str, list[tuple[Version, str]]] = {}
    text = path.read_text(encoding="utf-8")
    for block in re.split(r"\n(?=[A-Za-z0-9])", text):
        head = block.strip().splitlines()[0] if block.strip() else ""
        if not head or head.startswith(("#", "--")):
            continue
        match = re.match(r"^([A-Za-z0-9_.\-\[\]]+)==([^\s;\\]+)\s*(?:;\s*([^\\]+))?", head)
        assert match, f"{path.name}: {head!r} is not an exact pin"
        assert "--hash=sha256:" in block, f"{path.name}: {match.group(1)} has no hash"
        name = re.sub(r"\[.*\]", "", match.group(1)).lower().replace("_", "-")
        pins.setdefault(name, []).append((Version(match.group(2)), (match.group(3) or "").strip()))
    return pins


PROFILES = sorted(path.stem for path in LOCK.glob("*.in"))


def test_every_profile_has_its_lock_and_its_header():
    assert PROFILES, "no lock profiles"
    for name in PROFILES:
        lock = LOCK / f"{name}.txt"
        assert lock.exists(), f"run python scripts/lock_requirements.py --profile {name}"
        assert lock.read_text(encoding="utf-8").startswith(f"# generated by scripts/lock_requirements.py --profile {name};")


@pytest.mark.parametrize("name", PROFILES)
def test_each_lock_satisfies_every_requirement_of_its_inputs(name):
    pins = _pins(LOCK / f"{name}.txt")
    for requirement in _requirements(LOCK / f"{name}.in"):
        key = requirement.name.lower().replace("_", "-")
        assert key in pins, f"{name}.txt lacks {requirement.name}: rerun scripts/lock_requirements.py --profile {name}"
        for version, _marker in pins[key]:
            assert requirement.specifier.contains(version, prereleases=True), (
                f"{name}.txt pins {requirement.name}=={version}, outside {requirement.specifier}: "
                f"rerun python scripts/lock_requirements.py --profile {name}"
            )


def test_the_profiles_match_the_generator():
    import sys

    sys.path.insert(0, str(ROOT / "scripts"))
    import lock_requirements

    assert set(lock_requirements.PROFILES) == set(PROFILES)
    assert {name for name, spec in lock_requirements.PROFILES.items() if spec.torch_cpu} == {"ci", "runtime"}
    assert lock_requirements.PROFILES["compat"].python_version == "3.10"
