"""scripts/lock_requirements.py (V6.6.7, #361): the uv command per profile, the header, finding uv, and main."""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest
from script_loader import load_script, run_script

lock = load_script("lock_requirements")


def test_build_command_targets_311_universal_with_hashes():
    command = lock.build_command(lock.PROFILES["light"], uv="uv")
    assert command[:3] == ["uv", "pip", "compile"] and "--universal" in command and "--generate-hashes" in command
    assert command[command.index("--python-version") + 1] == "3.11"
    assert "--index-url" not in command


def test_torch_profiles_read_the_cpu_index_and_write_it_into_the_lock():
    command = lock.build_command(lock.PROFILES["ci"], uv="uv")
    assert command[command.index("--index-url") + 1] == lock.CPU_INDEX
    assert "--emit-index-url" in command and command[command.index("--index-strategy") + 1] == "unsafe-best-match"
    assert lock.build_command(lock.PROFILES["compat"])[lock.build_command(lock.PROFILES["compat"]).index("--python-version") + 1] == "3.10"


def test_write_header_prepends_once(tmp_path, monkeypatch):
    monkeypatch.setattr(lock, "LOCK_DIR", tmp_path)
    spec = lock.ProfileSpec("demo")
    spec.out_path.write_text("numpy==2.0 \\\n    --hash=sha256:" + "0" * 64 + "\n", encoding="utf-8")
    lock.write_header(spec)
    text = spec.out_path.read_text(encoding="utf-8")
    assert text.startswith("# generated by scripts/lock_requirements.py --profile demo;") and text.count("# generated") == 1
    assert spec.in_path == tmp_path / "demo.in"


def test_find_uv_on_path_next_to_python_or_nowhere(tmp_path, monkeypatch):
    assert lock.find_uv(lambda name: "/bin/uv") == "/bin/uv"
    fake_python = tmp_path / "python.exe"
    (tmp_path / "uv").write_text("", encoding="utf-8")
    monkeypatch.setattr(lock.sys, "executable", str(fake_python))
    assert lock.find_uv(lambda name: None) == str(tmp_path / "uv")
    (tmp_path / "uv").unlink()
    with pytest.raises(SystemExit, match="uv not found"):
        lock.find_uv(lambda name: None)


def test_main_runs_each_profile_with_an_in_file_and_stops_on_failure(tmp_path, monkeypatch, capsys):
    monkeypatch.setattr(lock, "LOCK_DIR", tmp_path)
    (tmp_path / "light.in").write_text("numpy\n", encoding="utf-8")
    monkeypatch.setattr(lock, "find_uv", lambda: "uv")
    calls: list = []

    def fake_run(command, cwd, check):
        calls.append(command)
        Path(command[command.index("-o") + 1]).write_text("numpy==2.0\n", encoding="utf-8")
        return subprocess.CompletedProcess(command, 0)

    assert lock.main(["--profile", "light", "--profile", "ci"], run=fake_run) == 0
    assert len(calls) == 1, "ci has no .in in the tmp dir, so it is skipped"
    assert (tmp_path / "light.txt").read_text(encoding="utf-8").startswith("# generated")
    assert lock.main(["--profile", "light"], run=lambda command, cwd, check: subprocess.CompletedProcess(command, 1)) == 1
    assert "uv failed" in capsys.readouterr().err
    assert lock.main(["--print"], run=fake_run) == 0
    assert "uv pip compile" in capsys.readouterr().out


def test_script_runs_as_main(monkeypatch, capsys):
    assert run_script("lock_requirements", ["--print", "--profile", "light"], monkeypatch) == 0
    assert "light.in" in capsys.readouterr().out
